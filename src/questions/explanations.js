const table=(headers,rows)=>`<div class="table-scroll"><table class="mini-table"><thead><tr>${headers.map(h=>`<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${rows.map(row=>`<tr>${row.map(v=>`<td>${esc(String(v))}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`;

function workedDetails(q){
    const text=q.stem.replace(/<\/?[a-z][^>]*>/gi,' '),arrays=[...text.matchAll(/\[([\d,\s-]+)\]/g)].map(m=>m[1].split(',').map(Number));
    if(q.id==='fill-binary'){
        const a=arrays.find(a=>a.length===7),target=Number(text.match(/查找 (\d+)/)[1]),rows=[];
        let lo=0,hi=a.length-1;
        while(lo<=hi){const mid=Math.floor((lo+hi)/2),value=a[mid];rows.push([lo,hi,mid,value,target===value?'相等，命中':target<value?`目标较小，hi=${mid-1}`:`目标较大，lo=${mid+1}`]);if(target===value)break;if(target<value)hi=mid-1;else lo=mid+1;}
        return table(['lo','hi','mid','A[mid]','比较与下一步'],rows);
    }
    if(q.id==='fill-bst'||q.id==='fill-traversal'){
        const a=arrays.find(a=>a.length>1);if(!a)return '';
        let root=null;const rows=[];
        for(const key of a){if(!root){root={key};rows.push([key,'空树',`设 ${key} 为根`]);continue;}let node=root;const path=[];while(true){path.push(node.key);const side=key<node.key?'left':'right';if(!node[side]){node[side]={key};rows.push([key,path.join(' → '),`作为 ${node.key} 的${side==='left'?'左':'右'}孩子`]);break;}node=node[side];}}
        let result=table(['插入键','经过的结点','插入位置'],rows);
        if(q.id==='fill-bst'){const target=Number(text.match(/查 (\d+)/)[1]),path=[];let node=root;while(node){path.push(node.key);if(node.key===target)break;node=target<node.key?node.left:node.right;}result+=`<p>查找路径：${path.join(' → ')}。包含命中结点，共 ${path.length} 次比较。</p>`;}
        return result;
    }
    if(q.id==='fill-next'||q.id==='calc-kmp'){
        const pat=text.match(/模式 ([a-z]+)/)?.[1];if(!pat)return '';
        const rows=[['0',pat[0],'空','约定','−1']];
        for(let j=1;j<pat.length;j++){const before=pat.slice(0,j);let k=0;for(let n=1;n<before.length;n++)if(before.slice(0,n)===before.slice(-n))k=n;rows.push([j,pat[j],before,k?before.slice(0,k):'无非空相同真前后缀',k]);}
        return table(['j','模式字符','j 之前的子串','最长相同真前后缀','next[j]'],rows);
    }
    if(q.id==='fill-huffman'||q.id==='calc-huffman'){
        const weights=arrays.find(a=>a.length===4);if(!weights)return '';
        let serial=0;const nodes=weights.map((w,i)=>({w,id:serial++,symbol:String.fromCharCode(65+i)})),codes={};
        while(nodes.length>1){nodes.sort((a,b)=>a.w-b.w||a.id-b.id);const left=nodes.shift(),right=nodes.shift();nodes.push({w:left.w+right.w,id:serial++,left,right});}
        const visit=(n,path)=>{if(n.symbol)codes[n.symbol]=path;else{visit(n.left,path+'0');visit(n.right,path+'1');}};visit(nodes[0],'');
        const rows=weights.map((w,i)=>{const symbol=String.fromCharCode(65+i),code=codes[symbol];return [symbol,w,code,code.length,`${w}×${code.length}=${w*code.length}`];});
        return table(['符号','出现次数','一组码字','编码位数','占用比特数'],rows)+`<p>将最后一列相加，得到 ${weights.reduce((sum,w,i)=>sum+w*codes[String.fromCharCode(65+i)].length,0)} bit。该结果只统计编码数据，未计码表。</p>`;
    }
    if(q.id==='calc-hash'||q.id==='hash-position'){
        const keys=arrays.find(a=>a.length>1);if(!keys)return '';
        const slots=Array(11).fill(null),rows=[];
        for(const key of keys){const home=key%7,path=[];for(let i=0;i<11;i++){const pos=(home+i)%11;path.push(`${pos}${slots[pos]===null?'（空）':`（已有 ${slots[pos]}）`}`);if(slots[pos]===null){slots[pos]=key;rows.push([key,home,path.join(' → '),pos,i+1]);break;}}}
        return table(['键','初始地址','实际探测过程','最终位置','探测次数'],rows);
    }
    if(q.id==='binary-asl'){
        const n=Number(text.match(/对 (\d+) 个/)[1]),rows=[];for(let level=1,count=1;count<=n;level++,count*=2)rows.push([level,count,level*count]);
        return table(['比较次数（层号）','该层元素数','比较次数贡献'],rows)+`<p>把第三列相加后除以 ${n}。每个元素等概率，所以按元素数加权，不能按层直接取平均。</p>`;
    }
    if(q.id==='fill-counting'){
        const a=arrays.find(a=>a.length>1),counts=Array(10).fill(0);for(const v of a)counts[v]++;
        return table(['值','出现次数','输出规则'],counts.map((count,value)=>[value,count,count?`按升序输出 ${count} 个 ${value}`:'跳过']));
    }
    if(q.id==='bubble-pass'){
        const a=[...arrays.find(a=>a.length>1)],rows=[];for(let i=0;i<a.length-1;i++){const left=a[i],right=a[i+1],swap=left>right;if(swap)[a[i],a[i+1]]=[right,left];rows.push([`${i} 与 ${i+1}`,`${left} 与 ${right}`,swap?'交换':'不交换',a.join(', ')]);}
        return table(['下标','本轮比较值','操作','操作后数组'],rows);
    }
    if(q.id==='intro-doubling'){
        const limit=Number(text.match(/i<=(\d+)/)[1]),values=[];for(let i=1;i<=limit;i*=2)values.push(i);
        return `<p>实际进入循环的 i 值为 ${values.join('、')}，共 ${values.length} 次。下一值 ${values.at(-1)*2} 已大于 ${limit}，不再进入循环。</p>`;
    }
    if(q.id==='fill-aoe'){
        const values=[...text.matchAll(/工期 (\d+)/g)].map(m=>Number(m[1])),[a,b,c]=values;
        return table(['事件','最早发生 ET','最晚发生 LT'],[['A',0,0],['B',a,c-b],['C',`max(${a}+${b},${c})=${c}`,c]])+`<p>B→C 的起点为 B、终点为 C，故 ES=${a}，LS=${c}−${b}=${c-b}，机动时间 ${c-b-a}。A→C 更长，B→C 并非关键活动。</p>`;
    }
    return '';
}

export function explainQuestion(q){
    const guide=guides[q.topicId];
    if(!guide)throw new Error('缺少知识点解析：'+q.topicId);
    const options=q.options?`<h3>逐项判断</h3><ol class="option-analysis">${q.options.map(o=>`<li><b>${o.id}．${esc(o.text)}（${o.correct?'应选':'不选'}）</b><p>${esc(o.explanation)}</p></li>`).join('')}</ol>`:'';
    const fills=q.answers?`<h3>各空对应关系</h3><ol>${q.answers.map(f=>`<li>${esc(f.label)}：<strong>${esc(f.accepted[0])}</strong>${f.accepted.length>1?'（也接受：'+f.accepted.slice(1).map(esc).join('、')+'）':''}</li>`).join('')}</ol>`:'';
    return `<h3>判断依据</h3><p>${guide[0]}</p><h3>本题解答与推导</h3>${q.solution}${workedDetails(q)}${options}${fills}<h3>易错点与适用条件</h3><p>${guide[1]}</p>`;
}
